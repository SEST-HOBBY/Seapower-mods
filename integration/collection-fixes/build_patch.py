def build_airbases():
    rank = load_rank()
    (OUT / "land_units").mkdir(parents=True, exist_ok=True)
    done = []
    for unit_id, mod in AIRBASE_RETUNE.items():
        owners = sorted((rank.get(p.parts[-3], 10**5), p.parts[-3], p)
                        for p in MODS.glob(f"*/land_units/{unit_id}.ini")
                        if not p.parts[-3].startswith("_"))
        if not owners:
            sys.exit(f"AIRBASE_RETUNE: no mod ships land_units/{unit_id}.ini any more")
        if owners[0][1] != mod:
            sys.exit(f"AIRBASE_RETUNE: {unit_id} is won by {owners[0][1]}, not {mod} - "
                     "re-check which copy the game loads before retuning it")
        src = read_file(owners[0][2])
        text, changes = airbase.retune(src)
        if not changes:
            sys.exit(f"AIRBASE_RETUNE: {unit_id} already carries every value - drop it")
        (OUT / "land_units" / f"{unit_id}.ini").write_text(
            airbase.header(unit_id, mod, changes) + text, encoding="utf-8")
        done.append(f"{unit_id} ({len(changes)})")
    return done


def build_stale_overwrites():
    """vessels_overwrite/<Euromod's file name>, retargeted - see STALE_OVERWRITES.
    Stops the build when Euromod fixes or drops a file, or the dead hull comes
    back, so an entry is deleted the day it is no longer needed."""
    out_dir = OUT / "vessels_overwrite"
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*_OVWR.ini"):
        stale.unlink()
    idx = hull_index()
    done = []
    for name, (old, new, why) in sorted(STALE_OVERWRITES.items()):
        src = MODS / EUROMOD_MAIN / "vessels_overwrite" / name
        if not src.is_file():
            sys.exit(f"{name}: Euromod Main Pack no longer ships it - drop it from STALE_OVERWRITES")
        text = read_file(src)
        if not text.lstrip("\ufeff").startswith(f"#!extend {old}"):
            sys.exit(f"{name}: Euromod changed its target - re-check, then drop or update the entry")
        old_id, new_id = (Path(t).stem for t in (old, new))
        if [c for c in idx.get(old_id, []) if c[1] != "_vanilla"]:
            sys.exit(f"{name}: a mod ships {old_id} again - drop it from STALE_OVERWRITES")
        if not idx.get(new_id):
            sys.exit(f"{name}: {new_id} is not shipped by any mod - pick another target")
        (out_dir / name).write_text(
            f"#!extend {new}\n\n"
            f"# SEST Collection Fixes: replaces Euromod Main Pack's {name}, which extends\n"
            f"# {old} - a hull no enabled mod ships, so the game built a unit with no\n"
            f"# names from the patch. {why}.\n"
            f"# No keys are set here.\n", encoding="utf-8")
        done.append(old_id)
    return done


def build_extends():
    """vessels_overwrite/<id>_CombatSystems_SEST.ini for every hull in EXTENDS."""
    idx, extended = hull_index(), extended_by_mods()
    vanilla_dir = MODS / "_vanilla" / "original" / "vessels"
    table = dict(EXTENDS)
    for uid in VANILLA_SAME:
        vt = read_file(vanilla_dir / f"{uid}.ini")
        m = re.search(r"^\[CombatSystem1\][^\n]*\n(?:(?!^\[).)*?^SystemName=(\S+)", vt, re.M | re.S)
        if not m:
            sys.exit(f"{uid}: vanilla's own file declares no combat system now - re-check")
        table[uid] = m.group(1)
    out_dir = OUT / "vessels_overwrite"
    out_dir.mkdir(parents=True, exist_ok=True)
    for stale in out_dir.glob("*_CombatSystems_SEST.ini"):
        stale.unlink()
    built = []
    for uid, profile in sorted(table.items()):
        cands = [c for c in idx.get(uid, []) if c[1] != "_vanilla"]
        if not cands:
            sys.exit(f"{uid}: no mod ships this hull (re-export, or drop it from EXTENDS)")
        r, mod, path = cands[0]
        text = read_file(path)
        if text.lstrip().startswith("#!"):
            sys.exit(f"{uid}: {mod}'s file is an alias/extend itself - extend the base instead")
        if not re.search(r"^UnitType=Vessel\s*$", text, re.M):
            sys.exit(f"{uid}: not UnitType=Vessel in {mod} - submarines take no profile here")
        own = re.search(r"^\[CombatSystem1\][^\n]*\n(?:(?!^\[).)*?^SystemName=([^\s/]+)",
                        text, re.M | re.S)
        if own and combat_profile_defined(own.group(1)):
            sys.exit(f"{uid}: {mod} now declares its own [CombatSystems] ({own.group(1)}) - "
                     "drop it from EXTENDS")
        elif own:
            # 6 Oct 2026: twelve hulls (Ford, Fujian 004, Kirov, Mogami, the French
            # pack) took [CombatSystems] blocks naming profiles - MU_SSDS_Carrier,
            # CMS_Horizon, SETIS_FDI and so on - that neither the game nor any mod
            # defines. A name that resolves to nothing is no choice to respect;
            # the extend keeps the SEST profile on the hull until the name exists.
            print(f"  {uid}: {mod}'s own combat system {own.group(1)} is defined nowhere - "
                  f"extended with {profile}")
        who = extended.get(f"vessels/{uid}.ini".lower())
        if who:
            sys.exit(f"{uid}: already extended by {who} - a second block would double it; "
                     "drop it from EXTENDS")
        why = (combat.PROFILES[profile][3] if profile in combat.PROFILES
               else combat.VANILLA_PROFILES.get(profile, "vanilla's own profile for this hull"))
        body = (f"#!extend vessels/{uid}.ini\n\n"
                f"# SEST Collection Fixes: {mod}'s {uid} declares no combat system, so the\n"
                f"# game would derive one from its service year. {profile}: {why}\n"
                + combat.combat_block(profile, "SEST Collection Fixes"))
        (out_dir / f"{uid}_CombatSystems_SEST.ini").write_text(body, encoding="utf-8")
        built.append(uid)
    return built


def read_file(p):
    return Path(p).read_text(encoding="utf-8-sig", errors="replace")


@functools.lru_cache(maxsize=None)
def combat_profiles_defined():
    """Every [section] name in a systems/ file of the game or any mod: the
    names a hull's SystemName can resolve to."""
    names = set()
    for f in list((MODS / "_vanilla" / "original" / "systems").glob("*.ini")) + list(MODS.glob("*/systems/*.ini")):
        names |= set(re.findall(r"^\[([^\]\n]+)\]", read_file(f), re.M))
    return names


def combat_profile_defined(name):
    return name in combat_profiles_defined() or name in combat.PROFILES


