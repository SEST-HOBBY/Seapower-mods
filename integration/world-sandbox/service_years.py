#!/usr/bin/env python3
"""Service years for the World campaign's shipyard, from the collection's own ServiceDate keys.

Dynamic Campaign Mod's catalogue entry has no date or label field, and its
`tier` is also the unlock rank, so the years cannot travel in campaign.json.
build_regions.py writes them instead as a committed runtime source,
integration/beta-feature-parity/runtime/WorldShipyardYears.cs, which
WorldShipyard.cs reads to order and label the shipyard cards. campaign.json
is not changed by this table.

Years come from the winning *_variants.ini of each ship catalogue unit, read
with the builder's own resolver (build_pack.winning). Aircraft are left out.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "integration" / "campaign"))
import build_pack as bp                      # noqa: E402  winning-file resolver

YEAR = 2028
TABLE = ROOT / "integration" / "beta-feature-parity" / "runtime" / "WorldShipyardYears.cs"
CAMPAIGN = HERE / "SEST_World_Campaign" / "dynamic_campaigns" / "sest-world-regions-2028" / "campaign.json"
SERVICE = re.compile(r"\s*ServiceDate\s*=\s*(\d{4})?\s*(?:\|\s*(\d{4})?)?")


def service_years(uid, aircraft, year=YEAR):
    """[first, last] over the winning variants/squadrons file, or None if it has no ServiceDate.

    first is 0 when no row gives a start year. last is None when any hull
    is open-ended or still serves in `year`.
    """
    rows = []
    for kind in (("aircraft",) if aircraft else ("vessels", "submarines")):
        f = bp.winning(f"{kind}/{uid}_{'squadrons' if kind == 'aircraft' else 'variants'}.ini")
        for line in (bp.read(f).splitlines() if f else []):
            m = SERVICE.match(line)
            if m and (m[1] or m[2]):
                rows.append((m[1] and int(m[1]), m[2] and int(m[2])))
    if not rows:
        return None
    starts = [a for a, _ in rows if a]
    return [min(starts) if starts else 0,
            None if any(b is None or b >= year for _, b in rows) else max(b for _, b in rows)]


def ship_years(campaign):
    """Ship catalogue unit -> (First, Last); 0 = unknown start / in service in YEAR."""
    out = {}
    for row in campaign["catalogue"]:
        if row.get("aircraft") or row.get("ground"):
            continue
        years = service_years(row["unit"], False)
        if years is not None:
            out[row["unit"]] = (years[0], years[1] or 0)
    return dict(sorted(out.items()))


def render(campaign):
    """The C# table, byte-identical for the same campaign and collection."""
    ships = ship_years(campaign)
    lift = sorted(campaign["ground"]["lift"])
    lines = [
        "using System.Collections.Generic;",
        "",
        "namespace Sest.RuntimeFixes;",
        "",
        "// GENERATED by integration/world-sandbox/build_regions.py (service_years.py).",
        "// Do not edit. Ship catalogue units of the World campaign with the first",
        "// and last ServiceDate year of their winning *_variants.ini. First=0: no",
        f"// start year given; Last=0: in service in {YEAR}. ShipsTabToo is the",
        "// campaign's ground.lift: lift ships listed under Ships as well as Amphibious.",
        "internal static class WorldShipyardYears",
        "{",
        "    internal static readonly Dictionary<string, (int First, int Last)> Ships = new()",
        "    {",
    ]
    lines += [f"        {{ {json.dumps(u)}, ({a}, {b}) }}," for u, (a, b) in ships.items()]
    lines += [
        "    };",
        "    internal static readonly HashSet<string> ShipsTabToo = new() { "
        + ", ".join(json.dumps(u) for u in lift) + " };",
        "}",
        "",
    ]
    return "\n".join(lines)


def write(campaign, path=TABLE):
    path.write_bytes(render(campaign).encode("ascii"))
    return path


if __name__ == "__main__":
    out = write(json.loads(CAMPAIGN.read_text(encoding="utf-8")))
    print(f"wrote {out}")
