#!/usr/bin/env python3
"""Bring the release's upload manifest back in line with the built pack.

docs/releases/20261107/upload-manifest.json lists every file of
integration/dist/SEST_Integration with its size and SHA-256. The owner's PC
toolkit holds the upload to it: tools/prepare-workshop-upload.ps1 refuses a
folder whose file count or any hash differs, and
tools/install-workshop-release-data.ps1 does the same before it copies the
release into the Workshop item. So a rebuild that changes one file leaves a
manifest the PC will refuse, and nothing here said so: until 13 Nov 2026 the
list was regenerated by hand after each rebuild, by no script in the
repository.

    python3 tools/refresh_upload_manifest.py           # rewrite the list
    python3 tools/refresh_upload_manifest.py --check   # exit 1 if it is out of date

Only "files" and "file_count" are rewritten. Every other field of the
manifest (the release revision, the plugin hashes, the ribbon and nation
tables) is somebody's statement about the release and is kept as it is. The
list is ordered as the committed one is, by path parts, and the file is
written as it has been: one line, compact separators, a trailing newline.

After a rewrite two texts quote the count and must follow it, which
tools/tests/test_campaign_runtime_awards.py checks: README-FIRST.txt
("VERIFIED: all N canonical upload files match the release manifest.") and
the validation.json block of the release branch (": N files match the
manifest").
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = "docs/releases/20261107/upload-manifest.json"
DIST = "integration/dist/SEST_Integration"


def listing(dist):
    """[{"path", "bytes", "sha256"}] for every file under dist, by path parts."""
    dist = Path(dist)
    paths = sorted(p.relative_to(dist) for p in dist.rglob("*") if p.is_file())
    return [{"path": p.as_posix(), "bytes": (dist / p).stat().st_size,
             "sha256": hashlib.sha256((dist / p).read_bytes()).hexdigest()} for p in paths]


def compare(manifest, files):
    """-> (added, removed, changed) paths of the built pack against the manifest's list."""
    old = {e["path"]: e for e in manifest["files"]}
    new = {e["path"]: e for e in files}
    return (sorted(set(new) - set(old)), sorted(set(old) - set(new)),
            sorted(p for p in set(new) & set(old) if new[p] != old[p]))


def refresh(root=ROOT, check=False, out=print):
    """Compare, and unless check rewrite. -> True when the manifest matched the pack."""
    root = Path(root)
    path = root / MANIFEST
    manifest = json.loads(path.read_text(encoding="utf-8"))
    files = listing(root / DIST)
    if not files:
        raise SystemExit(f"{DIST} holds no file: build the pack first (tools/build_all.py)")
    added, removed, changed = compare(manifest, files)
    same = not (added or removed or changed) and manifest.get("file_count") == len(files)
    out(f"{MANIFEST}: lists {manifest.get('file_count')} file(s); {DIST} holds {len(files)} "
        f"({len(added)} not listed, {len(removed)} listed and gone, {len(changed)} changed)")
    for label, items in (("not listed", added), ("gone", removed), ("changed", changed)):
        for item in items[:20]:
            out(f"   {label}: {item}")
        if len(items) > 20:
            out(f"   ... and {len(items) - 20} more {label}")
    if check or same:
        return same
    manifest["file_count"] = len(files)
    manifest["files"] = files
    path.write_text(json.dumps(manifest, separators=(",", ":")) + "\n", encoding="utf-8")
    out(f"rewrote {MANIFEST}: {len(files)} file(s). README-FIRST.txt and validation.json quote the count.")
    return False


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--check", action="store_true",
                        help="change nothing; exit 1 when the manifest does not match the built pack")
    args = parser.parse_args()
    same = refresh(check=args.check)
    if args.check and not same:
        print("Upload manifest: OUT OF DATE (run python3 tools/refresh_upload_manifest.py)")
        return 1
    if args.check:
        print("Upload manifest: matches the built pack")
    return 0


if __name__ == "__main__":
    sys.exit(main())
